/**
 * Clock abstraction enabling deterministic cooldown and timestamp testing in [RuleEngine].
 */
fun interface EngineClock {
    /**
     * Returns the current epoch time in milliseconds.
     *
     * Contract: Monotonically non-decreasing wall-clock or virtual test timestamp in milliseconds.
     * Failure modes: Does not throw.
     * Thread safety: Implementations must be thread-safe.
     */
    fun nowEpochMs(): Long
}

/**
 * Outcome returned by an [ActionExecutor] for a single [Action] step.
 */
sealed interface ActionExecutionOutcome {
    data class Success(
        val summary: String,
        val usedFallback: Boolean = false,
    ) : ActionExecutionOutcome

    data class Failure(
        val errorMessage: String,
    ) : ActionExecutionOutcome
}

/**
 * Executes a single [ActionType] on the host system.
 */
interface ActionExecutor {
    /**
     * The [ActionType] handled by this executor.
     */
    val supportedType: ActionType

    /**
     * Executes [action] in response to an optional [event].
     *
     * Contract: Performs the concrete action and returns [ActionExecutionOutcome.Success] or
     * [ActionExecutionOutcome.Failure].
     * Failure modes: Should capture expected domain failures as [ActionExecutionOutcome.Failure], while allowing
     * coroutine cancellation to propagate cleanly.
     * Thread safety: Must be safe to invoke from arbitrary coroutine dispatchers.
     */
    suspend fun execute(action: Action, event: TriggerEvent? = null): ActionExecutionOutcome

    /**
     * Describes what [action] would perform during a dry run without causing side effects.
     *
     * Contract: Pure human-readable summary of the planned operation with sensitive parameters redacted.
     * Failure modes: Never throws.
     * Thread safety: Stateless and thread-safe.
     */
    fun describeDryRun(action: Action): String {
        val safeConfig = LogRedactor.redactConfig(action.config)
        return "Would execute ${action.type.name} with config=$safeConfig"
    }
}

/**
 * Registry resolving an [ActionExecutor] for a requested [ActionType].
 */
interface ActionExecutorRegistry {
    /**
     * Looks up the registered [ActionExecutor] for [type], or `null` if none is bound.
     *
     * Contract: O(1) lookup by [ActionType].
     * Failure modes: Returns `null` when unregistered; never throws.
     * Thread safety: Immutable map lookup; completely thread-safe.
     */
    fun executorFor(type: ActionType): ActionExecutor?
}

/**
 * Default map-backed [ActionExecutorRegistry] built from DI multibindings.
 */
class MapActionExecutorRegistry(
    executors: Set<@JvmSuppressWildcards ActionExecutor>,
) : ActionExecutorRegistry {
    private val byType: Map<ActionType, ActionExecutor> = executors.associateBy { it.supportedType }

    /**
     * Returns the bound [ActionExecutor] for [type], or `null` if unavailable.
     *
     * Contract: Pure map lookup.
     * Failure modes: Never throws.
     * Thread safety: Immutable backing map; completely thread-safe.
     */
    override fun executorFor(type: ActionType): ActionExecutor? = byType[type]
}

/**
 * Sink receiving redacted [ExecutionLogEntry] records generated by [RuleEngine].
 */
fun interface ExecutionLogSink {
    /**
     * Persists a single [entry] to the rotating execution log.
     *
     * Contract: Stores [entry] after applying redaction invariants.
     * Failure modes: Implementations should handle storage I/O errors without crashing the caller.
     * Thread safety: Safe for concurrent coroutine invocation.
     */
    suspend fun append(entry: ExecutionLogEntry)
}

/**
 * Persists runtime rule execution metadata (cooldown timestamp, consecutive failure count, circuit-breaker disable).
 */
interface RuleExecutionStateStore {
    /**
     * Records a successful execution of [ruleId] at [triggeredAtEpochMs], resetting consecutive failures to zero.
     *
     * Contract: Updates `lastTriggeredEpochMs` and sets `consecutiveFailures = 0`.
     * Failure modes: Propagates cancellation; storage failures are logged by the implementation.
     * Thread safety: Safe for concurrent coroutine invocation.
     */
    suspend fun recordSuccess(ruleId: String, triggeredAtEpochMs: Long)

    /**
     * Increments consecutive failures for [rule], disabling the rule if [Rule.CIRCUIT_BREAKER_THRESHOLD] is reached.
     *
     * Contract: Atomically increments failure count, disables [rule] at threshold, and returns the updated count.
     * Failure modes: Propagates cancellation; storage failures are logged by the implementation.
     * Thread safety: Safe for concurrent coroutine invocation.
     */
    suspend fun recordFailure(rule: Rule): Int

    companion object {
        val NO_OP: RuleExecutionStateStore = object : RuleExecutionStateStore {
            override suspend fun recordSuccess(ruleId: String, triggeredAtEpochMs: Long) = Unit
            override suspend fun recordFailure(rule: Rule): Int = rule.consecutiveFailures + 1
        }
    }
}

/**
 * Notifies the user when the circuit breaker automatically disables a repeatedly failing [Rule].
 */
fun interface CircuitBreakerListener {
    /**
     * Invoked when [rule] reaches [consecutiveFailures] and is automatically disabled.
     *
     * Contract: Surfaces a non-intrusive user notification explaining why [rule] was paused.
     * Failure modes: Must never throw uncaught exceptions.
     * Thread safety: Safe for concurrent coroutine invocation.
     */
    suspend fun onCircuitBreakerTripped(rule: Rule, consecutiveFailures: Int, lastError: String)
}
